  /**
   * 학년군 + 교과 맥락에 맞는 도서관과 정보생활 성취기준 추천
   * guide.md 3.2절의 학년군 필터링 및 협력수업 키워드 가중치 규칙 구현
   */
  function recommendLibraryStandards(kb, grade, subject, area, topic, skills) {
    const band = gradeBandOf(grade || 4);
    const candidates = (kb.library.standards || []).filter(s => s.band === band);
    const contextStr = [
      subject ? subject.name : '',
      area ? area.name : '',
      topic || '',
      ...(skills || []),
      ...(area ? area.skills : []),
    ].join(' ');

    const scored = candidates.map(std => {
      let score = 10;
      // 영역 키워드 매칭
      Object.entries(LIB_AREA_WEIGHTS).forEach(([areaKey, words]) => {
        if (std.areaId.includes(areaKey)) {
          words.forEach(w => { if (contextStr.includes(w)) score += 4; });
        }
      });
      // 성취기준 본문 키워드 직접 매칭
      ['질문', '검색', '분류', '사실', '의견', '출처', '저작권', '비교', '그래픽', '산출물', '성찰', '그림책', '이야기책'].forEach(w => {
        if (contextStr.includes(w) && (std.text.includes(w) || std.desc.includes(w))) score += 5;
      });
      return { ...std, score };
    }).sort((a, b) => b.score - a.score);

    return scored.length ? scored : (kb.library.standards || []);
  }

