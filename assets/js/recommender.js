  /**
   * 선택한 학년·교과·단원 영역·지식요소·수행동사에 맞는 2022 개정 교과 성취기준 추천
   */
  function recommendSubjectStandards(kb, grade, subject, area, topic, knowledge, skills) {
    if (!subject) return [];
    const g = +grade || 4;
    const band = gradeBandOf(g);
    const curArea = area || (subject.areas && subject.areas[0]);
    if (!curArea) return [];

    const areaIdx = Math.max(0, (subject.areas || []).findIndex(a => a.id === curArea.id));
    const areaNoStr = String(areaIdx + 1).padStart(2, '0');

    // 학년군 코드 숫자 결정 (교과별 편제 학년군 반영)
    let gradePrefix = g <= 2 ? '2' : (g <= 4 ? '4' : '6');
    if (subject.key === 'integrated') gradePrefix = '2';
    else if (subject.key === 'practical') gradePrefix = '6';
    else if (!['korean', 'math'].includes(subject.key) && gradePrefix === '2') gradePrefix = '4';

    const subjChar = SUBJECT_CODE_PREFIX[subject.key] || subject.short.slice(0, 1);
    const templates = AREA_STANDARDS_MAP[curArea.id] || [];

    const contextStr = [
      topic || '',
      ...(knowledge || []),
      ...(skills || []),
    ].join(' ');

    const built = templates.map((tpl, idx) => {
      const codePrefix = tpl.prefix ? tpl.prefix : `${gradePrefix}${subjChar}`;
      const code = `[${codePrefix}${areaNoStr}-${tpl.no}]`;
      const linkedK = (tpl.kIdx || [idx]).map(i => curArea.knowledge[i]).filter(Boolean);
      const linkedS = [curArea.skills[idx % (curArea.skills.length || 1)]].filter(Boolean);

      let score = 20 - idx; // 기본 순서 가중치
      linkedK.forEach(k => {
        if ((knowledge || []).includes(k)) score += 18;
        if (contextStr.includes(k)) score += 10;
      });
      linkedS.forEach(s => {
        if ((skills || []).includes(s)) score += 12;
      });
      if (topic && (tpl.text.includes(topic) || tpl.desc.includes(topic))) {
        score += 15;
      }

      return {
        id: `SubjStd_${subject.key}_${curArea.id}_${tpl.no}`,
        code,
        text: tpl.text,
        desc: tpl.desc,
        band,
        areaId: curArea.id,
        areaName: curArea.name,
        subjectKey: subject.key,
        subjectName: subject.name,
        linkedKnowledge: linkedK,
        linkedSkills: linkedS,
        score,
      };
    });

    // 만약 템플릿이 없는 영역이 있을 경우 동적 폴백 생성
    if (!built.length) {
      const k0 = curArea.knowledge[0] || curArea.name;
      const k1 = curArea.knowledge[1] || '';
      const s0 = curArea.skills[0] || '탐구하기';
      built.push({
        id: `SubjStd_${subject.key}_${curArea.id}_01`,
        code: `[${gradePrefix}${subjChar}${areaNoStr}-01]`,
        text: `${k0}${k1 ? ' 및 ' + k1 : ''}의 의미와 특징을 이해하고 실생활 사례를 통해 ${s0.replace(/하기$/, '한다')}.`,
        desc: `${subject.name} '${curArea.name}' 영역의 핵심 아이디어를 바탕으로 지식·이해 요소와 과정·기능을 통합적으로 함양한다.`,
        band,
        areaId: curArea.id,
        areaName: curArea.name,
        subjectKey: subject.key,
        subjectName: subject.name,
        linkedKnowledge: [k0, k1].filter(Boolean),
        linkedSkills: [s0],
        score: 20,
      });
    }

    return built.sort((a, b) => b.score - a.score);
  }

